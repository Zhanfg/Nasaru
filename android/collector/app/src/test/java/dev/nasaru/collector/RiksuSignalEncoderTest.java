package dev.nasaru.collector;

import static org.junit.Assert.assertArrayEquals;

import org.junit.Test;

public final class RiksuSignalEncoderTest {
    @Test
    public void packageAddedGoldenFrameMatchesRust() {
        SignalEvent event = SignalEvent.packageAdded(42, 9, true);
        byte[] frame = RiksuSignalEncoder.encode(7, event);
        byte[] expected = new byte[] {
                0x52, 0x4b, 0x53, 0x55, 0x01, 0x00, 0x10, 0x00,
                0x00, 0x00, 0x00, 0x00, 0x12, 0x00, 0x00, 0x00,
                0x07, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
                0x09, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
                0x01, 0x00, 0x01, 0x00, 0x05,
                0x02, 0x00, 0x04, 0x00, 0x2a, 0x00, 0x00, 0x00,
                0x08, 0x00, 0x01, 0x00, 0x01,
        };
        assertArrayEquals(expected, frame);
    }
}
